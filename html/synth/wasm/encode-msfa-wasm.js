// Encode WASM binary as a JS file for AudioWorklet loading
// Usage: node encode-wasm.js msfa.wasm

if (process.argv.length != 3) {
  console.log("usage: node encode-wasm.js mymodule.wasm");
  process.exit(1);
}

const fs = require('fs');
const wasmName = process.argv[2];
const wasmData = fs.readFileSync(wasmName);
const wasmStr = wasmData.join(",");

const out = `// Auto-generated by encode-wasm.js — do not edit
if (!AudioWorkletGlobalScope._msfaWasmBinary) {
  AudioWorkletGlobalScope._msfaWasmBinary = new Uint8Array([${wasmStr}]);
}
`;
fs.writeFileSync(wasmName + ".js", out);
console.log(`Encoded ${wasmName} (${wasmData.length} bytes) → ${wasmName}.js`);
